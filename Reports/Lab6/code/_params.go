// hexInt разбирает шестнадцатеричную запись числа.
func hexInt(s string) *big.Int {
	n, ok := new(big.Int).SetString(s, 16)
	if !ok {
		panic("ec: invalid hexadecimal constant " + s)
	}
	return n
}
